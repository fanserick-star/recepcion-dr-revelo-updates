import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const path="recepcion/app/tv_display.html";
const s=readFileSync(path,"utf8"), v=JSON.parse(readFileSync("recepcion/app/recepcion-version.json","utf8"));
assert.equal(v.version,"4.8.39");
const script=s.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script);
new vm.Script(script,{filename:path});
// El cambio sólo aplica si center tiene clase idle-clock-active.
assert.match(s,/\.center\.idle-clock-active\s*\{\s*background:linear-gradient\(165deg,#fffefa/);
assert.match(s,/\.center\.idle-clock-active \.stage\s*\{\s*padding:0/);
assert.match(s,/\.center\.idle-clock-active:before/);
assert.match(s,/\.idle-clock-scene\s*\{[^}]*padding:clamp\(14px,2\.1vh,30px\)/);
assert.match(s,/\.idle-clock-face\s*\{[^}]*width:min\(36vh,28vw\)/);
assert.match(s,/@media\(max-height:540px\)/);
assert.match(s,/<stop offset="100%" stop-color="#122e48"\/>/);
assert.match(s,/r="194" fill="#cdb78a" opacity="\.88"/);
assert.match(s,/class="idle-clock-time"/);
assert.match(s,/class="idle-clock-date"/);
assert.match(s,/class="idle-clock-signature"/);
assert.match(script,/function idle\(force\)/);
assert.match(script,/if\(state&&state\.next_waiting_turn\)/);
assert.match(script,/if\(s\.mode==='calling'&&s\.turn\)/);
assert.match(script,/else if\(s\.mode==='attending'&&s\.turn\)/);
assert.match(script,/function announceTurn\(turn\)/);
assert.match(script,/if\(s\.event_id&&s\.event_id!==lastEvent\)/);
assert.match(script,/if\(source==='live'&&!s\.history_online/);
assert.equal((s.match(/idle-clock-scene/g)||[]).length>=2,true);
console.log("TV_WHITE_PREMIUM_VISUAL_ONLY_NO_CLIPPED_LABELS_CLOCK_AND_TURN_FLOW_OK");
